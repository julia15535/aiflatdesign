def to_english(ru_text: str) -> tuple[str, str, bool]:
    """Переводит русское название объекта на английский.

    Returns:
        (english_term, canonical_ru, is_known) — если is_known=False, передаём
        исходник в качестве английского и предупреждаем что не уверены.
    """
    key = ru_text.strip().lower().replace("ё", "е")
    # Точное совпадение
    for variant, (en, canonical) in _MAPPING.items():
        if variant.replace("ё", "е") == key:
            return en, canonical, True
    # Поиск по подстроке (например «диван» в «угловой диван» уже искали выше,
    # но «большой диван» → диван)
    for variant, (en, canonical) in _MAPPING.items():
        v = variant.replace("ё", "е")
        if len(v) >= 4 and v in key:
            return en, canonical, True
    # Не нашли — возвращаем исходник для подсказки ИИ-промпта
    return ru_text.strip(), ru_text.strip(), False


def known_examples(limit: int = 10) -> list[str]:
    """Несколько примеров для подсказки пользователю в боте."""
